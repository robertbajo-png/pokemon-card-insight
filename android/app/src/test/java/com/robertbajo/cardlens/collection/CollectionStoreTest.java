package com.robertbajo.cardlens.collection;

import static org.junit.Assert.*;

import android.content.Context;
import android.database.Cursor;
import android.database.sqlite.SQLiteDatabase;
import java.io.File;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.UUID;
import java.util.concurrent.Callable;
import java.util.concurrent.ExecutionException;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.TimeUnit;
import org.json.JSONObject;
import org.junit.After;
import org.junit.Before;
import org.junit.Test;
import org.junit.runner.RunWith;
import org.robolectric.RobolectricTestRunner;
import org.robolectric.RuntimeEnvironment;
import org.robolectric.annotation.Config;
import org.robolectric.annotation.SQLiteMode;

/** Uses real Room + native SQLite on disposable Robolectric disk files, not an in-memory fake. */
@RunWith(RobolectricTestRunner.class)
@Config(sdk = 36, manifest = Config.NONE)
@SQLiteMode(SQLiteMode.Mode.NATIVE)
public class CollectionStoreTest {
    private Context context;
    private ExecutorService worker;
    private final List<CollectionDatabase> databases = new ArrayList<>();
    private final List<String> names = new ArrayList<>();

    @Before
    public void setUp() {
        context = RuntimeEnvironment.getApplication();
        worker = Executors.newSingleThreadExecutor();
    }

    @After
    public void tearDown() throws Exception {
        try {
            io(() -> {
                for (CollectionDatabase database : databases) database.close();
                return null;
            });
        } finally {
            worker.shutdown();
            worker.awaitTermination(20, TimeUnit.SECONDS);
            // Every name was generated by this test; never access the installed app's data.
            for (String name : names) context.deleteDatabase(name);
        }
    }

    private String databaseName() {
        // Robolectric already gives every test its own disposable directory. Keep the
        // filename short: its method-name/random parent can otherwise hit Windows MAX_PATH.
        String name = "fixture-" + names.size() + ".db";
        String path = context.getDatabasePath(name).getAbsolutePath();
        if (File.separatorChar == '\\') {
            assertTrue("Synthetic Room path must stay at most 240 characters on Windows; got "
                + path.length() + ": " + path, path.length() <= 240);
        }
        names.add(name);
        return name;
    }

    private CollectionDatabase open(String name) {
        CollectionDatabase database = CollectionDatabase.open(context, name);
        databases.add(database);
        return database;
    }

    private CollectionStore store(CollectionDatabase database) {
        // A fixed clock proves that repeated updates still get increasing timestamps.
        return new CollectionStore(database, () -> 1_700_000_000_000L);
    }

    private <T> T io(Callable<T> action) throws Exception {
        try {
            return worker.submit(action).get(30, TimeUnit.SECONDS);
        } catch (ExecutionException error) {
            if (error.getCause() instanceof Exception) throw (Exception) error.getCause();
            if (error.getCause() instanceof Error) throw (Error) error.getCause();
            throw error;
        }
    }

    private static JSONObject input() throws Exception {
        return new JSONObject()
            .put("name", "ピカチュウ")
            .put("setId", "jp-sv2a")
            .put("setName", "Pokémon Card 151")
            .put("cardNumber", "025")
            .put("catalogueCardId", "jp-sv2a-025")
            .put("language", "ja")
            .put("variant", "normal")
            .put("condition", "near_mint")
            .put("quantity", 2)
            .put("location", "Pärm 1")
            .put("notes", "\n\t原文を保存\r\n");
    }

    private static CollectionFields fields() throws Exception {
        return CollectionFields.parse(input());
    }

    private void failure(String code, Callable<?> operation) {
        CollectionFailure error = assertThrows(CollectionFailure.class, () -> io(operation));
        assertEquals(code, error.code);
        assertNull(error.getCause());
    }

    @Test
    public void survivesDiskCloseAndReopenWithExactJapaneseIdsAndNotes() throws Exception {
        String name = databaseName();
        CollectionDatabase database = open(name);
        CollectionStore first = store(database);
        String id = UUID.randomUUID().toString().toUpperCase(java.util.Locale.ROOT);
        CollectionCard saved = io(() -> first.createCard(id, fields()));
        io(() -> { database.close(); return null; });
        File file = context.getDatabasePath(name);
        assertTrue(file.isFile());
        assertTrue(file.length() > 0);

        CollectionStore reopened = store(open(name));
        List<CollectionCard> cards = io(reopened::listCards);
        assertEquals(1, cards.size());
        CollectionCard actual = cards.get(0);
        assertEquals(id, actual.id);
        assertEquals("ピカチュウ", actual.name);
        assertEquals("jp-sv2a-025", actual.catalogueCardId);
        assertEquals("025", actual.cardNumber);
        assertEquals("\n\t原文を保存\r\n", actual.notes);
        assertEquals(saved.createdAt, actual.createdAt);
        assertEquals(saved.updatedAt, actual.updatedAt);
        assertEquals(1, actual.revision);
        JSONObject bridged = CardLensCollectionPlugin.cardJson(actual);
        assertEquals(15, bridged.length());
        assertEquals(id, bridged.getString("id"));
        assertEquals(actual.createdAt, bridged.getLong("createdAt"));
        assertEquals(actual.notes, bridged.getString("notes"));
    }

    @Test
    public void separateDatabasesNeverShareCardsEvenWithTheSameId() throws Exception {
        CollectionStore robert = store(open(databaseName()));
        CollectionStore leonard = store(open(databaseName()));
        String id = UUID.randomUUID().toString();
        io(() -> robert.createCard(id, fields()));
        assertTrue(io(leonard::listCards).isEmpty());
        io(() -> leonard.createCard(id, CollectionFields.parse(input().put("quantity", 7))));
        assertEquals(2, io(robert::listCards).get(0).quantity);
        assertEquals(7, io(leonard::listCards).get(0).quantity);
    }

    @Test
    public void createRetriesAreIdempotentAndRejectConflicts() throws Exception {
        CollectionStore store = store(open(databaseName()));
        String id = "card-" + UUID.randomUUID();
        CollectionCard first = io(() -> store.createCard(id, fields()));
        CollectionCard retry = io(() -> store.createCard(id, fields()));
        assertEquals(id, retry.id);
        assertEquals(first.createdAt, retry.createdAt);
        assertEquals(first.updatedAt, retry.updatedAt);
        assertEquals(first.revision, retry.revision);
        failure("CONFLICT", () -> store.createCard(id, CollectionFields.parse(input().put("quantity", 3))));
        failure("CONFLICT", () -> store.createCard(id, CollectionFields.parse(input().put("notes", "原文を保存"))));
        assertEquals(1, io(store::listCards).size());
        assertEquals(2, io(store::listCards).get(0).quantity);
    }

    @Test
    public void updatesAndDeletesUseCompareAndSwapAndMonotonicTimestamps() throws Exception {
        String name = databaseName();
        CollectionStore editorA = store(open(name));
        CollectionStore editorB = store(open(name));
        String id = UUID.randomUUID().toString();
        CollectionCard original = io(() -> editorA.createCard(id, fields()));
        CollectionCard edited = io(() -> editorB.updateCard(id, 1, CollectionFields.parse(input().put("quantity", 5))));
        assertEquals(2, edited.revision);
        assertEquals(original.createdAt, edited.createdAt);
        assertTrue(edited.updatedAt > original.updatedAt);
        failure("CONFLICT", () -> editorA.updateCard(id, 1, fields()));
        failure("CONFLICT", () -> { editorA.deleteCard(id, 1); return null; });
        assertEquals(5, io(editorA::listCards).get(0).quantity);
        CollectionCard next = io(() -> editorA.updateCard(id, 2, fields()));
        assertEquals(3, next.revision);
        assertTrue(next.updatedAt > edited.updatedAt);
        io(() -> { editorB.deleteCard(id, 3); return null; });
        assertTrue(io(editorA::listCards).isEmpty());
        failure("NOT_FOUND", () -> editorA.updateCard(id, 3, fields()));
        failure("NOT_FOUND", () -> { editorA.deleteCard(id, 3); return null; });
    }

    @Test
    public void listingIsStableAndLatestUpdatedComesFirst() throws Exception {
        CollectionStore store = store(open(databaseName()));
        String first = "00000000-0000-0000-0000-000000000001";
        String second = "00000000-0000-0000-0000-000000000002";
        io(() -> store.createCard(second, fields()));
        io(() -> store.createCard(first, fields()));
        assertEquals(first, io(store::listCards).get(0).id);
        io(() -> store.updateCard(second, 1, fields()));
        assertEquals(second, io(store::listCards).get(0).id);
        assertEquals(second, io(store::listCards).get(0).id);
    }

    @Test
    public void normalizesHumanWhitespaceWithoutChangingOpaqueIdsOrNotes() throws Exception {
        CollectionStore store = store(open(databaseName()));
        JSONObject raw = input()
            .put("name", "\ufeff\u00a0 ピカチュウ \u3000")
            .put("setName", "  Pokémon Card 151\u00a0")
            .put("cardNumber", " 025 ")
            .put("variant", " normal ")
            .put("location", "\u2000Pärm 1\ufeff")
            .put("setId", " JP/セット ")
            .put("catalogueCardId", " Card.ID_025!? ");
        CollectionCard card = io(() -> store.createCard(UUID.randomUUID().toString(), CollectionFields.parse(raw)));
        assertEquals("ピカチュウ", card.name);
        assertEquals("Pokémon Card 151", card.setName);
        assertEquals("025", card.cardNumber);
        assertEquals("normal", card.variant);
        assertEquals("Pärm 1", card.location);
        assertEquals(" JP/セット ", card.setId);
        assertEquals(" Card.ID_025!? ", card.catalogueCardId);
        assertEquals("\n\t原文を保存\r\n", card.notes);
        CollectionCard nullable = io(() -> store.createCard(UUID.randomUUID().toString(),
            CollectionFields.parse(input().put("setId", JSONObject.NULL).put("catalogueCardId", JSONObject.NULL))));
        assertTrue(CardLensCollectionPlugin.cardJson(nullable).isNull("setId"));
        assertTrue(CardLensCollectionPlugin.cardJson(nullable).isNull("catalogueCardId"));
    }

    @Test
    public void invalidSnapshotsAndRevisionsLeaveAllStoredDataUnchanged() throws Exception {
        CollectionStore store = store(open(databaseName()));
        String id = UUID.randomUUID().toString();
        io(() -> store.createCard(id, fields()));
        List<JSONObject> invalid = new ArrayList<>(Arrays.asList(
            input().put("name", "\u00a0\ufeff"),
            input().put("name", "a".repeat(121)),
            input().put("setId", " "),
            input().put("catalogueCardId", "x\u0000y"),
            input().put("quantity", 1.5),
            input().put("quantity", "2"),
            input().put("quantity", 10000),
            input().put("language", "JP"),
            input().put("condition", "NM"),
            input().put("location", "one\ntwo"),
            input().put("notes", "a\u0085b"),
            input().put("notes", "a".repeat(2001)),
            input().put("surprise", "not a field")
        ));
        JSONObject missing = input();
        missing.remove("setId");
        invalid.add(missing);
        for (JSONObject value : invalid) {
            failure("VALIDATION", () -> store.updateCard(id, 1, CollectionFields.parse(value)));
            failure("VALIDATION", () -> store.createCard(UUID.randomUUID().toString(), CollectionFields.parse(value)));
        }
        failure("VALIDATION", () -> store.createCard("../not-a-uuid", fields()));
        failure("VALIDATION", () -> store.updateCard(id, 0, fields()));
        failure("VALIDATION", () -> { store.deleteCard(id, -1); return null; });
        assertEquals(1, io(store::listCards).size());
        CollectionCard unchanged = io(store::listCards).get(0);
        assertEquals(1, unchanged.revision);
        assertEquals(2, unchanged.quantity);
        assertEquals("\n\t原文を保存\r\n", unchanged.notes);
    }

    @Test
    public void failedDatabaseWriteRollsBackAndExposesNoSqlDetails() throws Exception {
        CollectionDatabase database = open(databaseName());
        CollectionStore store = store(database);
        String id = UUID.randomUUID().toString();
        CollectionCard before = io(() -> store.createCard(id, fields()));
        io(() -> {
            database.getOpenHelper().getWritableDatabase().execSQL(
                "CREATE TRIGGER fail_test_write BEFORE UPDATE ON collection_cards "
                    + "BEGIN SELECT RAISE(ABORT, 'test-only SQL detail'); END"
            );
            return null;
        });
        failure("STORAGE_UNAVAILABLE", () -> store.updateCard(id, 1, CollectionFields.parse(input().put("quantity", 8))));
        CollectionCard after = io(store::listCards).get(0);
        assertEquals(before.revision, after.revision);
        assertEquals(before.updatedAt, after.updatedAt);
        assertEquals(before.quantity, after.quantity);
    }

    @Test
    public void unsupportedFutureVersionFailsClosedAndPreservesOriginalFile() throws Exception {
        String name = databaseName();
        CollectionDatabase database = open(name);
        CollectionStore original = store(database);
        String id = UUID.randomUUID().toString();
        io(() -> original.createCard(id, fields()));
        io(() -> { database.close(); return null; });
        File file = context.getDatabasePath(name);
        io(() -> {
            try (SQLiteDatabase sqlite = SQLiteDatabase.openDatabase(file.getPath(), null, SQLiteDatabase.OPEN_READWRITE)) {
                sqlite.setVersion(99);
            }
            return null;
        });
        byte[] before = Files.readAllBytes(file.toPath());
        CollectionDatabase incompatible = open(name);
        CollectionStore oldApp = store(incompatible);
        failure("STORAGE_UNAVAILABLE", oldApp::listCards);
        io(() -> { incompatible.close(); return null; });
        assertTrue(file.isFile());
        assertArrayEquals(before, Files.readAllBytes(file.toPath()));
        io(() -> {
            try (SQLiteDatabase sqlite = SQLiteDatabase.openDatabase(file.getPath(), null, SQLiteDatabase.OPEN_READONLY);
                 Cursor cursor = sqlite.rawQuery("SELECT id, name FROM collection_cards", null)) {
                assertEquals(99, sqlite.getVersion());
                assertTrue(cursor.moveToFirst());
                assertEquals(id, cursor.getString(0));
                assertEquals("ピカチュウ", cursor.getString(1));
            }
            return null;
        });
    }

    @Test
    public void corruptFileFailsClosedWithoutDeletionOrAutomaticRecovery() throws Exception {
        String name = databaseName();
        File file = context.getDatabasePath(name);
        assertTrue(file.getParentFile().isDirectory() || file.getParentFile().mkdirs());
        byte[] original = new byte[4096];
        Arrays.fill(original, (byte) 0x6b);
        Files.write(file.toPath(), original);
        CollectionDatabase corrupt = open(name);
        CollectionStore store = store(corrupt);
        failure("STORAGE_UNAVAILABLE", store::listCards);
        io(() -> { corrupt.close(); return null; });
        assertTrue(file.isFile());
        assertArrayEquals(original, Files.readAllBytes(file.toPath()));
    }
}
